"""Определение чужого языка в ответе бармена.

Модуль намеренно не зависит от Django: его использует и рабочий код, и
офлайн-бенчмарк промптов в `deployment/ollama/`, который запускается без
настроек проекта. Раньше проверка была скопирована в трёх местах и успела
разойтись.
"""

import re

# Иероглифы, пунктуация CJK и полноширинные формы: ответ с ними нельзя
# публиковать как русский. Пунктуация нужна отдельно — строка вида
# «Проверь порт сервера。」 состоит из кириллицы и всё же не является русской.
HAN_CHARACTERS = re.compile(r"[\u3000-\u303f\u3400-\u9fff\uff00-\uffef]")
CYRILLIC_CHARACTERS = re.compile(r"[А-Яа-яЁё]")


def needs_language_retry(content: str) -> bool:
    """Ответ без русской речи или с китайскими символами просим переписать."""
    return bool(HAN_CHARACTERS.search(content)) or not bool(
        CYRILLIC_CHARACTERS.search(content)
    )
