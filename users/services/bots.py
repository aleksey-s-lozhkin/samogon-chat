"""Кто в системе персонаж, а не гость.

Семён и Птица-Говорун — обычные учётные записи, но не люди. Их нельзя
пригласить в закрытую беседу, их не показывают в списке гостей и их не считают
гостями, когда решается, можно ли птице говорить.

Личные сообщения — отдельный вопрос, и ответ у персонажей разный. Бармен
собеседник: ему пишут наедине, и он отвечает (кнопка в панели и отдельный
эндпоинт). Птица не собеседник: ей писать некуда. Поэтому здесь два набора имён,
а не один.

Пока персонаж был один, проверки писались по месту и сравнивали имя с
`BARTENDER_USERNAME`. Со вторым персонажем такая проверка размножилась бы:
десять мест, в каждом легко забыть про новое имя. Поэтому одним списком
управляет этот модуль, а всё остальное спрашивает `is_bot`.
"""

from __future__ import annotations

from django.conf import settings


def bot_usernames() -> set[str]:
    """Имена всех персонажей. Пустые значения настроек пропускаются."""
    names = {settings.BARTENDER_USERNAME, settings.BIRD_USERNAME}
    return {name for name in names if name}


def conversational_bot_usernames() -> set[str]:
    """Персонажи, которые отвечают на личные вопросы.

    Бармен — собеседник: ему пишут наедине, и это его работа. Птица — нет:
    она чирикает в комнате, личной переписки у неё не бывает. Разделение
    важно: без него запрет «персонажам не пишут» заодно ломал бы вопросы
    Семёну, а это существующая функция с кнопкой и отдельным эндпоинтом.
    """
    return {settings.BARTENDER_USERNAME} if settings.BARTENDER_USERNAME else set()


def unavailable_bot_usernames() -> set[str]:
    """Персонажи, которым нельзя написать лично и которых нет в списках выбора."""
    return bot_usernames() - conversational_bot_usernames()


def is_bot(user) -> bool:
    """Персонаж ли это. Для анонимного и отсутствующего пользователя — нет."""
    if user is None:
        return False
    if getattr(user, "is_anonymous", False):
        return False
    return getattr(user, "username", "") in bot_usernames()
